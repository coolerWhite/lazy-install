# --- log ---------------------------------------------------------------
# Что делает: печатает обычное сообщение с пометкой [INFO].
#
# Как вызывают:   log "Ставлю пакеты"
# Что видно:      [INFO] Ставлю пакеты
#
# Псевдокод:
#   функция log:
#       напечатать "[INFO] " + первый аргумент + перевод строки
#
# Подсказки:
#   - первый аргумент функции лежит в $1
#   - printf вызывается БЕЗ скобок: printf 'шаблон' аргументы
#       printf '%s\n' "текст"        -> напечатает текст и перевод строки
#       printf 'Hi, %s\n' "Vic"      -> Hi, Vic
log() {
    printf '[INFO] %s\n' "$1"
}


# --- warn --------------------------------------------------------------
# Что делает: то же, что log, но пометка [WARN].
# Для чего: «что-то не так, но продолжаем».
#
# Как вызывают:   warn "yay не найден, пропускаю AUR"
# Что видно:      [WARN] yay не найден, пропускаю AUR
#
# Псевдокод:
#   функция warn:
#       напечатать "[WARN] " + $1  -> в поток ошибок (stderr)
#
# Подсказка: чтобы вывод ушёл в stderr, в конце команды пишут  >&2
#   Зачем: обычный вывод (stdout) и ошибки (stderr) можно разделить,
#   например ./post_install.sh 2> errors.log соберёт только ошибки.

warn(){
    printf '[WARN] %s\n' "$1" >&2
}


# --- error -------------------------------------------------------------
# Что делает: как warn, но пометка [ERROR]. Тоже в stderr.
#
# Псевдокод:
#   функция error:
#       напечатать "[ERROR] " + $1  -> в stderr

error(){
    printf '[ERROR] %s\n' "$1" >&2
}


# --- die ---------------------------------------------------------------
# Что делает: печатает ошибку и ОСТАНАВЛИВАЕТ весь скрипт.
# Для чего: «дальше продолжать бессмысленно».
#
# Как вызывают:   die "Не запускай меня через sudo"
#
# Псевдокод:
#   функция die:
#       вызвать error с тем же текстом      <- используем свою же функцию
#       выйти из скрипта с кодом 1          <- команда exit
#
# Код выхода: 0 = всё хорошо, любое другое число = ошибка.

die(){
    error "$1"
    exit 1
}


# --- has_cmd -----------------------------------------------------------
# Что делает: отвечает на вопрос «установлена ли программа?».
# Ничего не печатает, только «да/нет» через код возврата.
#
# Как вызывают:
#   if has_cmd yay; then
#       log "yay уже есть"
#   fi
#
# Псевдокод:
#   функция has_cmd:
#       спросить у bash, знает ли он команду $1   <- command -v
#       вывод этой проверки выкинуть              <- > /dev/null
#       (код возврата command -v и станет ответом функции)
#
# Попробуй в терминале, чтобы понять:
#   command -v git ; echo $?
#   command -v nosuchprogram ; echo $?

has_cmd(){
    command -v "$1" > /dev/null
    return $?
}


